"""
dashboard.py - Builds the Narrative Radar page (dashboard.html) that watch.py opens in your browser.

Plain English: watch.py does the checking; this file turns what it found into one good-looking
page with a card per topic, a 48-hour chart, the mood of the coverage, the newest headlines,
and your alert history. The page refreshes itself every minute while watch.py keeps running.

Standard terms: this is a static HTML "dashboard" generated by Python (templating), with
inline SVG "sparklines" (tiny line charts) and an auto-refresh <meta> tag.
"""

import csv
import html
import os
from datetime import datetime

PAGE = "dashboard.html"


def mood_label(tone):
    """Average sentiment of the last 24h of headlines and posts, from -1 (fear/anger) to +1 (positive)."""
    if tone is None:
        return "NO READ", "quiet"
    if tone >= 0.05:
        return "CALM / POSITIVE", "calm"
    if tone > -0.05:
        return "NEUTRAL", "calm"
    if tone > -0.25:
        return "TENSE", "warn"
    return "HOSTILE / FEARFUL", "hot"


PLAT = {"Google News": "GN", "Bing News": "BING", "Hacker News": "HN", "Mastodon": "MASTO", "Reddit": "REDDIT", "GDELT": "GDELT"}


def chips(r):
    e = html.escape
    counts, status = r.get("counts") or {}, r.get("status") or {}
    out = []
    for name in ("Google News", "Bing News", "Hacker News", "Mastodon", "Reddit", "GDELT"):
        st = status.get(name)
        if name == "GDELT":
            label, cls = (st or "—"), ("on" if st == "ok" else "off")
        elif isinstance(st, int):
            n = counts.get(name, 0)
            label, cls = str(n), ("on" if n else "zero")
        else:
            label, cls = (st or "—"), "off"
        out.append(f'<span class="chip {cls}" title="{e(name)}">{PLAT[name]} <b>{e(label)}</b></span>')
    return "".join(out)


def first_seen(r):
    f = r.get("first") or []
    if len(f) < 2:
        return ""
    parts = [f'{PLAT.get(p, p)} {datetime.fromtimestamp(ts):%I:%M %p}' for p, ts in f[:4]]
    return '<p class="first"><span>FIRST SEEN</span>' + " → ".join(html.escape(x) for x in parts) + "</p>"


def sparkline(values, w=260, h=56):
    """A tiny line chart of articles per hour over the last 48 hours, newest on the right."""
    if not values:
        return '<svg class="spark" viewBox="0 0 260 56"></svg>'
    top = max(values) or 1
    step = w / max(1, len(values) - 1)
    pts = [(i * step, h - 4 - (v / top) * (h - 10)) for i, v in enumerate(values)]
    line = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
    area = f"0,{h} " + line + f" {w},{h}"
    lx, ly = pts[-1]
    return (f'<svg class="spark" viewBox="0 0 {w} {h}" preserveAspectRatio="none" aria-hidden="true">'
            f'<polygon points="{area}" class="area"/><polyline points="{line}" class="line"/>'
            f'<circle cx="{lx:.1f}" cy="{ly:.1f}" r="3.2" class="dot"/></svg>')


def read_alerts(path, limit=15):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return rows[-limit:][::-1]


def card(r):
    e = html.escape
    status, cls = ("SPIKE", "hot") if r["spike"] else ("RISING", "warn") if r["z"] >= r["z_cut"] / 2 else ("QUIET", "quiet")
    if r.get("stale"):
        status, cls = ("SAVED " + r["as_of"], "quiet") if r.get("as_of") else ("WAITING", "quiet")
    mood, mcls = mood_label(r.get("tone"))
    tone_txt = "—" if r.get("tone") is None else f'{r["tone"]:+.2f}'
    zbar = max(0, min(100, r["z"] / max(r["z_cut"], 0.1) * 100))
    heads = "".join(
        f'<li><a href="{e(h.get("url", ""))}" target="_blank" rel="noopener">{e(h.get("title", "").strip())}</a>'
        f'<span><i>{e(PLAT.get(h.get("platform", ""), "NEWS"))}</i> {e(h.get("domain", ""))}</span></li>' for h in (r.get("headlines") or [])
    ) or '<li class="none">No headlines in the last 24 hours.</li>'
    if r.get("stale") and r.get("as_of"):
        err = f'<p class="err">No source answered this round. Showing the reading from {e(r["as_of"])}.</p>'
    elif r.get("stale"):
        err = '<p class="err">No reading yet. Trying again next round.</p>'
    else:
        err = ""
    return f"""
  <article class="card {cls}">
    <header><h2>{e(r["query"])}</h2><span class="tag {cls}">{status}</span></header>
    {err}
    <div class="nums">
      <div><b>{r["latest"]:.0f}</b><small>items last hour</small></div>
      <div><b>{r["mean"]:.1f}</b><small>normal hour</small></div>
      <div><b>{r["z"]:.1f}</b><small>z-score</small></div>
    </div>
    <div class="zbar"><i style="width:{zbar:.0f}%"></i><em>alert line</em></div>
    {sparkline(r.get("hours", []))}
    <p class="sig">signal: {e(r.get("signal") or "—")}</p>
    <div class="mood {mcls}"><span>MOOD</span><b>{mood}</b><small>score {tone_txt}</small></div>
    <div class="chips">{chips(r)}</div>
    {first_seen(r)}
    <ul class="heads">{heads}</ul>
  </article>"""


def viral(trends):
    """The VIRAL NOW strip: what is blowing up everywhere, whatever the topic. AI items are flagged."""
    if not trends:
        return ""
    e = html.escape
    cols = []
    for name, items in trends.items():
        if isinstance(items, str):
            body = f'<li class="none">{e(name)} {e(items)} this round.</li>'
        else:
            body = "".join(
                f'<li class="{"ai" if it.get("ai") else ""}"><a href="{e(it["url"])}" target="_blank" rel="noopener">'
                f'{"<i>AI</i>" if it.get("ai") else ""}{e(it["title"])}</a>'
                f'<span>{e(it.get("extra", ""))}{" · " + e(it["note"]) if it.get("note") else ""}</span></li>'
                for it in items[:8])
        cols.append(f'<section class="vcol"><h4>{e(name.upper())}</h4><ol>{body}</ol></section>')
    ai_count = sum(1 for v in trends.values() if not isinstance(v, str) for it in v if it.get("ai"))
    return (f'<h3>VIRAL NOW <span class="aiN">{ai_count} AI item{"s" if ai_count != 1 else ""} trending</span></h3>'
            f'<div class="viral">{"".join(cols)}</div><h3>YOUR WATCHLIST</h3>')


